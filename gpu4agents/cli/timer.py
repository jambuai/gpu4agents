"""A per-user timer that runs `gpu sweep --apply`: systemd on Linux, launchd on macOS.

One command covers every project: the sweep guards each project in
``$GPU_HOME/projects.json`` with its own config, so the unit does not depend
on its working directory. Neither a systemd user unit nor a LaunchAgent needs
root, and neither inherits the shell's environment: credentials must live in
``~/.gpu/credentials`` or the project ``.env``. Writing the files is all this
module does; enabling them is left to the printed command.
"""

from __future__ import annotations

import os
import shlex
import sys
from pathlib import Path
from typing import Optional
from xml.sax.saxutils import escape

from ..core.paths import gpu_home

UNIT_NAME = "jambu-gpu-sweep"
LAUNCHD_LABEL = "ai.jambu.gpu-sweep"
# A stuck provider API must not wedge the oneshot (and with it every later run).
START_TIMEOUT = "10min"


def unit_dir() -> Path:
    base = os.environ.get("XDG_CONFIG_HOME")
    root = Path(base).expanduser() if base else Path.home() / ".config"
    return root / "systemd" / "user"


def unit_paths() -> tuple[Path, Path]:
    directory = unit_dir()
    return directory / f"{UNIT_NAME}.service", directory / f"{UNIT_NAME}.timer"


def _specifiers(value: str) -> str:
    # systemd expands %h, %u, ... in unit values; a literal % must be doubled.
    return value.replace("%", "%%")


def _quote(arg: str) -> str:
    """One ExecStart= argument: % and $ escaped, quoted when it needs it."""
    arg = _specifiers(arg).replace("$", "$$")
    if not arg or any(c in arg for c in " \t\"'\\;"):
        return '"' + arg.replace("\\", "\\\\").replace('"', '\\"') + '"'
    return arg


def _environment(name: str, value: str) -> str:
    text = _specifiers(f"{name}={value}").replace("\\", "\\\\").replace('"', '\\"')
    return f'Environment="{text}"'


def render_units(
    *, every_s: float, python: str, jambu_home: Optional[str] = None
) -> tuple[str, str]:
    lines = [
        "# Generated by `gpu sweep --install-timer`. Remove with --uninstall-timer.",
        "[Unit]",
        "Description=gpu4agents: guard every registered project and clean up orphans",
        "",
        "[Service]",
        "Type=oneshot",
        "WorkingDirectory=~",
        f"TimeoutStartSec={START_TIMEOUT}",
    ]
    if jambu_home:
        lines.append(_environment("GPU_HOME", jambu_home))
    # No "-" prefix: a failing sweep must show up as a failed unit.
    lines.append("ExecStart=" + " ".join(_quote(a) for a in [python, "-m", "gpu4agents", "sweep", "--apply"]))
    lines.append("")
    service = "\n".join(lines)
    seconds = max(60, int(every_s))
    timer = "\n".join(
        [
            "# Generated by `gpu sweep --install-timer`.",
            "[Unit]",
            f"Description=Run {UNIT_NAME}.service every {seconds}s",
            "",
            "[Timer]",
            "OnActiveSec=60s",
            f"OnUnitActiveSec={seconds}s",
            "AccuracySec=30s",
            f"Unit={UNIT_NAME}.service",
            "",
            "[Install]",
            "WantedBy=timers.target",
            "",
        ]
    )
    return service, timer


def legacy_guard_configs(service: Path) -> list[Path]:
    """Config paths of the per-project `guard` lines older units carried."""
    if not service.is_file():
        return []
    found = []
    for line in service.read_text().splitlines():
        if not line.startswith("ExecStart="):
            continue
        try:
            args = shlex.split(line[len("ExecStart="):].lstrip("-"))
        except ValueError:
            continue
        if args and args[-1] == "guard" and "--config" in args:
            index = args.index("--config") + 1
            if index < len(args):
                found.append(Path(args[index].replace("%%", "%")))
    return found


def _platform() -> str:
    return sys.platform


def _launchd() -> bool:
    return _platform() == "darwin"


def plist_path() -> Path:
    return Path.home() / "Library" / "LaunchAgents" / f"{LAUNCHD_LABEL}.plist"


def render_plist(*, every_s: float, python: str, jambu_home: Optional[str] = None) -> str:
    """A LaunchAgent that runs the sweep every ``every_s`` seconds and at login."""
    log = str(gpu_home() / "logs" / "sweep.log")

    def string(value: str) -> str:
        return f"<string>{escape(value)}</string>"

    args = "".join(
        f"\n    {string(a)}" for a in [python, "-m", "gpu4agents", "sweep", "--apply"]
    )
    env = ""
    if jambu_home:
        env = (
            "\n  <key>EnvironmentVariables</key>\n  <dict>\n"
            f"    <key>GPU_HOME</key>{string(jambu_home)}\n  </dict>"
        )
    return f"""<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<!-- Generated by gpu4agents (gpu sweep, install-timer). Remove with uninstall-timer. -->
<plist version="1.0">
<dict>
  <key>Label</key>{string(LAUNCHD_LABEL)}
  <key>ProgramArguments</key>
  <array>{args}
  </array>
  <key>WorkingDirectory</key>{string(str(Path.home()))}
  <key>StartInterval</key><integer>{max(60, int(every_s))}</integer>
  <key>RunAtLoad</key><true/>
  <key>ProcessType</key><string>Background</string>
  <key>StandardOutPath</key>{string(log)}
  <key>StandardErrorPath</key>{string(log)}{env}
</dict>
</plist>
"""


def is_installed() -> bool:
    """Whether the sweep timer is on: the LaunchAgent on macOS, an enabled unit on Linux.

    Writing the units is not enough: until `systemctl --user enable` links
    the timer into timers.target.wants, nothing runs it.
    """
    if _launchd():
        return plist_path().is_file()
    timer = unit_paths()[1]
    return timer.is_file() and (timer.parent / "timers.target.wants" / timer.name).exists()


def install_timer(every_s: float, python: Optional[str] = None) -> dict:
    """Write (or rewrite) the units, or the LaunchAgent on macOS."""
    python = python or sys.executable
    jambu_home = os.environ.get("GPU_HOME") or os.environ.get("JAMBU_HOME") or None
    if _launchd():
        path = plist_path()
        path.parent.mkdir(parents=True, exist_ok=True)
        (gpu_home() / "logs").mkdir(parents=True, exist_ok=True)
        path.write_text(render_plist(every_s=every_s, python=python, jambu_home=jambu_home))
        quoted = shlex.quote(str(path))
        return {
            "scheduler": "launchd",
            "files": [str(path)],
            "plist": str(path),
            "every_s": max(60, int(every_s)),
            "legacy_guard_configs": [],
            # bootout first: re-running --install-timer must reload the new file.
            "enable": (
                f"launchctl bootout gui/$(id -u) {quoted} 2>/dev/null; "
                f"launchctl bootstrap gui/$(id -u) {quoted}"
            ),
        }
    service_path, timer_path = unit_paths()
    legacy = legacy_guard_configs(service_path)
    service, timer = render_units(every_s=every_s, python=python, jambu_home=jambu_home)
    service_path.parent.mkdir(parents=True, exist_ok=True)
    service_path.write_text(service)
    timer_path.write_text(timer)
    return {
        "scheduler": "systemd",
        "files": [str(service_path), str(timer_path)],
        "service": str(service_path),
        "timer": str(timer_path),
        "every_s": max(60, int(every_s)),
        "legacy_guard_configs": [str(p) for p in legacy],
        "enable": f"systemctl --user daemon-reload && systemctl --user enable --now {UNIT_NAME}.timer",
    }


def uninstall_timer() -> dict:
    removed = []
    if _launchd():
        path = plist_path()
        if path.exists():
            path.unlink()
            removed.append(str(path))
        return {
            "removed": removed,
            "disable": f"launchctl bootout gui/$(id -u)/{LAUNCHD_LABEL}",
        }
    for path in unit_paths():
        if path.exists():
            path.unlink()
            removed.append(str(path))
    return {
        "removed": removed,
        "disable": f"systemctl --user disable --now {UNIT_NAME}.timer; systemctl --user daemon-reload",
    }


# ---------------------------------------------------------------------------
# the queue coordinator as a service (`gpu queue install-service`)
# ---------------------------------------------------------------------------


def queue_service_name(project_dir: Path) -> str:
    """One service per project: the folder name plus a short hash of its full path."""
    import hashlib
    import re

    resolved = str(Path(project_dir).resolve())
    slug = re.sub(r"[^A-Za-z0-9_.-]+", "-", Path(resolved).name).strip("-.") or "project"
    return f"jambu-gpu-queue-{slug[:32]}-{hashlib.sha256(resolved.encode()).hexdigest()[:6]}"


def queue_unit_path(project_dir: Path) -> Path:
    return unit_dir() / f"{queue_service_name(project_dir)}.service"


def queue_plist_path(project_dir: Path) -> Path:
    return Path.home() / "Library" / "LaunchAgents" / f"ai.jambu.{queue_service_name(project_dir)}.plist"


def render_queue_unit(*, python: str, project_dir: Path, jambu_home: Optional[str] = None) -> str:
    """A systemd user unit that runs `gpu queue run` in the project and restarts it when it fails."""
    lines = [
        "# Generated by `gpu queue install-service`. Remove with --uninstall.",
        "[Unit]",
        f"Description=gpu4agents queue coordinator for {_specifiers(str(project_dir))}",
        "",
        "[Service]",
        "Type=simple",
        f"WorkingDirectory={_specifiers(str(project_dir))}",
    ]
    if jambu_home:
        lines.append(_environment("GPU_HOME", jambu_home))
    lines += [
        "ExecStart=" + " ".join(_quote(a) for a in [python, "-m", "gpu4agents", "queue", "run"]),
        "Restart=on-failure",
        "RestartSec=10",
        "",
        "[Install]",
        "WantedBy=default.target",
        "",
    ]
    return "\n".join(lines)


def render_queue_plist(*, python: str, project_dir: Path, jambu_home: Optional[str] = None) -> str:
    """A LaunchAgent that runs `gpu queue run` in the project, restarted when it exits with an error."""
    name = queue_service_name(project_dir)
    log = str(gpu_home() / "logs" / f"{name}.log")

    def string(value: str) -> str:
        return f"<string>{escape(value)}</string>"

    args = "".join(f"\n    {string(a)}" for a in [python, "-m", "gpu4agents", "queue", "run"])
    env = ""
    if jambu_home:
        env = (
            "\n  <key>EnvironmentVariables</key>\n  <dict>\n"
            f"    <key>GPU_HOME</key>{string(jambu_home)}\n  </dict>"
        )
    return f"""<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<!-- Generated by gpu4agents (gpu queue install-service). Remove with --uninstall. -->
<plist version="1.0">
<dict>
  <key>Label</key>{string("ai.jambu." + name)}
  <key>ProgramArguments</key>
  <array>{args}
  </array>
  <key>WorkingDirectory</key>{string(str(project_dir))}
  <key>RunAtLoad</key><true/>
  <key>KeepAlive</key>
  <dict>
    <key>SuccessfulExit</key><false/>
  </dict>
  <key>ProcessType</key><string>Background</string>
  <key>StandardOutPath</key>{string(log)}
  <key>StandardErrorPath</key>{string(log)}{env}
</dict>
</plist>
"""


def install_queue_service(project_dir: Path, python: Optional[str] = None) -> dict:
    """Write the service file; enabling it is left to the printed command."""
    python = python or sys.executable
    project_dir = Path(project_dir).resolve()
    jambu_home = os.environ.get("GPU_HOME") or os.environ.get("JAMBU_HOME") or None
    name = queue_service_name(project_dir)
    if _launchd():
        path = queue_plist_path(project_dir)
        path.parent.mkdir(parents=True, exist_ok=True)
        (gpu_home() / "logs").mkdir(parents=True, exist_ok=True)
        path.write_text(render_queue_plist(python=python, project_dir=project_dir, jambu_home=jambu_home))
        quoted = shlex.quote(str(path))
        return {
            "scheduler": "launchd", "name": name, "files": [str(path)],
            "enable": f"launchctl bootout gui/$(id -u) {quoted} 2>/dev/null; launchctl bootstrap gui/$(id -u) {quoted}",
        }
    path = queue_unit_path(project_dir)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(render_queue_unit(python=python, project_dir=project_dir, jambu_home=jambu_home))
    return {
        "scheduler": "systemd", "name": name, "files": [str(path)],
        "enable": f"systemctl --user daemon-reload && systemctl --user enable --now {name}.service",
    }


def uninstall_queue_service(project_dir: Path) -> dict:
    project_dir = Path(project_dir).resolve()
    name = queue_service_name(project_dir)
    path = queue_plist_path(project_dir) if _launchd() else queue_unit_path(project_dir)
    removed = []
    if path.exists():
        path.unlink()
        removed.append(str(path))
    disable = (
        f"launchctl bootout gui/$(id -u)/ai.jambu.{name}" if _launchd()
        else f"systemctl --user disable --now {name}.service; systemctl --user daemon-reload"
    )
    return {"removed": removed, "disable": disable}
