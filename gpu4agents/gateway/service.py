"""A per-project local service that runs ``gpu gateway start``: systemd on Linux,
launchd on macOS.

Unlike the sweep timer (one oneshot for all projects), the gateway is bound to
one project's model, so its unit is per-project and pins the project directory
as its working directory. It is a long-lived service: ``Type=simple`` with
``Restart=always`` so a crash respawns, and ``WantedBy=default.target`` plus
``loginctl enable-linger`` so it survives logout and reboot. The gateway only
reads the project's ``gpu.yaml`` and ``.gpu/state.json`` (never provider
credentials), so the unit needs no secrets in its environment.

Writing the files is all this module does; enabling them is the printed command.
"""

from __future__ import annotations

import hashlib
import os
import re
import sys
from pathlib import Path
from typing import Optional

PREFIX = "jambu-gpu-gateway"
RESTART_SEC = 2


def _slug(project_dir: Path) -> str:
    """A stable, filesystem-safe id for a project: its basename plus a path hash."""
    base = re.sub(r"[^a-zA-Z0-9]+", "-", project_dir.name).strip("-").lower() or "project"
    digest = hashlib.sha1(str(project_dir.resolve()).encode()).hexdigest()[:8]
    return f"{base}-{digest}"


def unit_name(project_dir: Path) -> str:
    return f"{PREFIX}-{_slug(project_dir)}"


def unit_dir() -> Path:
    base = os.environ.get("XDG_CONFIG_HOME")
    root = Path(base).expanduser() if base else Path.home() / ".config"
    return root / "systemd" / "user"


def unit_path(project_dir: Path) -> Path:
    return unit_dir() / f"{unit_name(project_dir)}.service"


def _specifiers(value: str) -> str:
    return value.replace("%", "%%")


def _quote(arg: str) -> str:
    arg = _specifiers(arg).replace("$", "$$")
    if not arg or any(c in arg for c in " \t\"'\\;"):
        return '"' + arg.replace("\\", "\\\\").replace('"', '\\"') + '"'
    return arg


def _environment(name: str, value: str) -> str:
    text = _specifiers(f"{name}={value}").replace("\\", "\\\\").replace('"', '\\"')
    return f'Environment="{text}"'


def render_unit(*, project_dir: Path, python: str, gpu_home: Optional[str] = None) -> str:
    exec_args = [python, "-m", "gpu4agents", "gateway", "start"]
    lines = [
        f"# Generated by `gpu gateway install` for {project_dir}. Remove with `gpu gateway uninstall`.",
        "[Unit]",
        "Description=gpu4agents: local gateway (stable loopback endpoint that follows the machine)",
        "After=network-online.target",
        "",
        "[Service]",
        "Type=simple",
        f"WorkingDirectory={_specifiers(str(project_dir))}",
        "Restart=always",
        f"RestartSec={RESTART_SEC}",
    ]
    if gpu_home:
        lines.append(_environment("GPU_HOME", gpu_home))
    lines.append("ExecStart=" + " ".join(_quote(a) for a in exec_args))
    lines += ["", "[Install]", "WantedBy=default.target", ""]
    return "\n".join(lines)


def _is_linux() -> bool:
    return sys.platform.startswith("linux")


def install_service(project_dir: Path, python: Optional[str] = None) -> dict:
    """Write (or rewrite) the per-project unit and return how to enable it."""
    if not _is_linux():
        raise NotImplementedError("gateway install currently supports Linux (systemd) only")
    python = python or sys.executable
    gpu_home = os.environ.get("GPU_HOME") or os.environ.get("JAMBU_HOME") or None
    path = unit_path(project_dir)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(render_unit(project_dir=project_dir, python=python, gpu_home=gpu_home))
    name = unit_name(project_dir)
    return {
        "scheduler": "systemd",
        "unit": name,
        "file": str(path),
        # enable-linger so it runs without an active login (survives reboot).
        "enable": (
            f"loginctl enable-linger $(whoami); "
            f"systemctl --user daemon-reload && systemctl --user enable --now {name}.service"
        ),
    }


def uninstall_service(project_dir: Path) -> dict:
    name = unit_name(project_dir)
    path = unit_path(project_dir)
    removed = []
    if path.exists():
        path.unlink()
        removed.append(str(path))
    return {
        "removed": removed,
        "unit": name,
        "disable": f"systemctl --user disable --now {name}.service; systemctl --user daemon-reload",
    }


def is_installed(project_dir: Path) -> bool:
    path = unit_path(project_dir)
    wants = path.parent / "default.target.wants" / path.name
    return path.is_file() and wants.exists()
